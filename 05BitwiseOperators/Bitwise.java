// package 05BitwiseOperators;

public class Bitwise {
    public static void main(String args[]){
        int a=10;
        int b=20;
        //bitwise operators
        System.out.println(a&b); 
        System.out.println(a|b);
        System.out.println(a^b);
        System.out.println(~a);
        System.out.println(a<<2);
        System.out.println(a>>2);
        System.out.println(a>>>2);
    }
    
}
