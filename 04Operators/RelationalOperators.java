// package 04Operators;

public class RelationalOperators {
    public static void main(String args[]){
        int a=10;
        int b=20;
        //relational operators
        System.out.println(a==b);
        System.out.println(a!=b);
        System.out.println(a>b);
        System.out.println(a<b);
        System.out.println(a>=b);
        System.out.println(a<=b);

        //logical operators
        boolean x=true;
        boolean y=false;
        System.out.println(x&&y);
        System.out.println(x||y);
        System.out.println(!x);

        
        
    
    }
    
}
